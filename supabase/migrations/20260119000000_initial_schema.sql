CREATE OR REPLACE FUNCTION calculate_pay_package(
  p_job_id text,
  p_state text,
  p_city text,
  p_profession text,
  p_specialty text,
  p_target_gross numeric,
  p_hours_per_week integer DEFAULT 36
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  v_taxable_hourly numeric;
  v_meals_weekly numeric;
  v_housing_weekly numeric;
  v_total_stipend numeric;
  v_gross_weekly numeric;
  v_state_tax_rate numeric;
BEGIN
  v_state_tax_rate := 0.25;
  CASE 
    WHEN p_state IN ('CA', 'NY', 'MA') THEN
      v_meals_weekly := 350;
      v_housing_weekly := 1500;
    WHEN p_state IN ('TX', 'FL', 'AZ') THEN
      v_meals_weekly := 300;
      v_housing_weekly := 1200;
    ELSE
      v_meals_weekly := 325;
      v_housing_weekly := 1350;
  END CASE;
  v_total_stipend := v_meals_weekly + v_housing_weekly;
  v_taxable_hourly := (p_target_gross - v_total_stipend) / p_hours_per_week;
  IF v_taxable_hourly < 25 THEN
    v_taxable_hourly := 25;
  END IF;
  v_gross_weekly := (v_taxable_hourly * p_hours_per_week) + v_total_stipend;
  RETURN jsonb_build_object(
    'job_id', p_job_id,
    'taxable_hourly', ROUND(v_taxable_hourly, 2),
    'meals_weekly', ROUND(v_meals_weekly, 2),
    'housing_weekly', ROUND(v_housing_weekly, 2),
    'total_stipend', ROUND(v_total_stipend, 2),
    'gross_weekly', ROUND(v_gross_weekly, 2)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.bulk_update_extension_stage(
  engagement_ids bigint[],
  new_stage text
)
RETURNS TABLE (
  engagement_id bigint,
  extension_stage text,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  IF new_stage NOT IN ('not_started', 'outreach', 'interested', 'requested', 'signed') THEN
    RAISE EXCEPTION 'Invalid extension_stage value: %', new_stage;
  END IF;

  RETURN QUERY
  UPDATE public.engagements
  SET
    extension_stage = new_stage,
    updated_at = NOW()
  WHERE id = ANY(engagement_ids)
  RETURNING id, engagements.extension_stage, engagements.updated_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.toggle_assignment_flag(
  engagement_id bigint,
  flag_name text,
  flag_value boolean
)
RETURNS TABLE (
  id bigint,
  is_looking_for_new_facility boolean,
  is_exiting boolean,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  IF flag_name NOT IN ('looking', 'exiting') THEN
    RAISE EXCEPTION 'Invalid flag_name: %. Must be "looking" or "exiting"', flag_name;
  END IF;

  IF flag_name = 'looking' THEN
    RETURN QUERY
    UPDATE public.engagements
    SET
      is_looking_for_new_facility = flag_value,
      updated_at = NOW()
    WHERE engagements.id = engagement_id
    RETURNING
      engagements.id,
      engagements.is_looking_for_new_facility,
      engagements.is_exiting,
      engagements.updated_at;
  ELSIF flag_name = 'exiting' THEN
    RETURN QUERY
    UPDATE public.engagements
    SET
      is_exiting = flag_value,
      updated_at = NOW()
    WHERE engagements.id = engagement_id
    RETURNING
      engagements.id,
      engagements.is_looking_for_new_facility,
      engagements.is_exiting,
      engagements.updated_at;
  END IF;
END;
$$;

