CREATE OR REPLACE VIEW follow_ups_dashboard AS
SELECT 
  f.id,
  f.candidate_id,
  f.recruiter_id,
  f.follow_up_type,
  f.scheduled_date,
  f.completed,
  f.completed_at,
  f.notes,
  f.created_at,
  f.updated_at,
  p.name AS candidate_name,
  p.email AS candidate_email,
  p.phone AS candidate_phone,
  p.specialty AS candidate_specialty,
  p.profession AS candidate_profession,
  p.status AS candidate_status,
  p.nova_url AS candidate_nova_url,
  u.email AS recruiter_email,
  COALESCE(u.raw_user_meta_data->>'full_name', u.email) AS recruiter_name
FROM follow_ups f
JOIN prospects p ON f.candidate_id = p.candidate_id
JOIN auth.users u ON f.recruiter_id = u.id;

CREATE OR REPLACE VIEW priority_interested_clicks AS
SELECT 
  ic.*,
  CASE 
    WHEN ic.last_note_date >= NOW() - INTERVAL '7 days' THEN true
    ELSE false
  END AS recruiter_contacted_recently,
  EXTRACT(DAY FROM NOW() - ic.application_date::timestamptz)::integer AS days_since_application
FROM interested_clicks ic
WHERE ic.status != 'Closed'
ORDER BY ic.application_date DESC;

